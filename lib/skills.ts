const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");

const MATCHERS = GROUPS.map(([name, ...aliases]) => {
  const alts = [name, ...aliases].map((a) => esc(a.toLowerCase())).join("|");
  return { name, re: new RegExp(`(?<![a-z0-9+#.])(?:${alts})(?![a-z0-9+#]|\\.[a-z])`, "i") };
});

export const ALL_SKILLS = GROUPS.map((g) => g[0]);

/** Returns canonical skill names found in the text, in dictionary order. */
export function findSkills(text: string): string[] {
  return MATCHERS.filter((m) => m.re.test(text)).map((m) => m.name);
}

